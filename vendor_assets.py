"""
vendor_assets.py - fetch and verify the front-end assets served locally
=======================================================================
`templates/index.html` used to load Leaflet, Leaflet-Draw and Font Awesome
from unpkg.com and cdnjs at runtime. That meant executing third-party code
fetched live on every page load, and it made the app impossible to run in an
isolated deployment.

Those files now live under `static/vendor/` and are served by this app.

This script exists so that vendoring is REPRODUCIBLE and AUDITABLE. An NCSC
reviewer will ask where 20 third-party files came from; without this, the
answer is "someone downloaded them once". Running it writes
`static/vendor/MANIFEST.txt` recording every URL, version, size and SHA-256.

Usage
-----
    python vendor_assets.py            # fetch anything missing, write manifest
    python vendor_assets.py --verify   # check on-disk files against manifest
    python vendor_assets.py --force    # re-fetch everything

Needs internet. Run once on a connected machine, then ship `static/vendor/`.
"""

import argparse
import hashlib
import os
import ssl
import sys
import urllib.request

# Pinned versions. Bump deliberately, then re-run and commit the new manifest.
LEAFLET = "1.9.4"
LEAFLET_DRAW = "1.0.4"
FONT_AWESOME = "6.5.1"

BASE = os.path.dirname(os.path.abspath(__file__))
VENDOR = os.path.join(BASE, "static", "vendor")
MANIFEST = os.path.join(VENDOR, "MANIFEST.txt")

UNPKG = "https://unpkg.com"
CDNJS = "https://cdnjs.cloudflare.com/ajax/libs"

ASSETS = [
    # (url, destination relative to static/vendor)
    (f"{UNPKG}/leaflet@{LEAFLET}/dist/leaflet.css", "leaflet/leaflet.css"),
    (f"{UNPKG}/leaflet@{LEAFLET}/dist/leaflet.js", "leaflet/leaflet.js"),
    (f"{UNPKG}/leaflet@{LEAFLET}/dist/images/marker-icon.png", "leaflet/images/marker-icon.png"),
    (f"{UNPKG}/leaflet@{LEAFLET}/dist/images/marker-icon-2x.png", "leaflet/images/marker-icon-2x.png"),
    (f"{UNPKG}/leaflet@{LEAFLET}/dist/images/marker-shadow.png", "leaflet/images/marker-shadow.png"),
    (f"{UNPKG}/leaflet@{LEAFLET}/dist/images/layers.png", "leaflet/images/layers.png"),
    (f"{UNPKG}/leaflet@{LEAFLET}/dist/images/layers-2x.png", "leaflet/images/layers-2x.png"),

    (f"{UNPKG}/leaflet-draw@{LEAFLET_DRAW}/dist/leaflet.draw.css", "leaflet-draw/leaflet.draw.css"),
    (f"{UNPKG}/leaflet-draw@{LEAFLET_DRAW}/dist/leaflet.draw.js", "leaflet-draw/leaflet.draw.js"),
    (f"{UNPKG}/leaflet-draw@{LEAFLET_DRAW}/dist/images/spritesheet.png", "leaflet-draw/images/spritesheet.png"),
    (f"{UNPKG}/leaflet-draw@{LEAFLET_DRAW}/dist/images/spritesheet-2x.png", "leaflet-draw/images/spritesheet-2x.png"),
    (f"{UNPKG}/leaflet-draw@{LEAFLET_DRAW}/dist/images/spritesheet.svg", "leaflet-draw/images/spritesheet.svg"),

    (f"{CDNJS}/font-awesome/{FONT_AWESOME}/css/all.min.css", "font-awesome/all.min.css"),
]
for _f in ("fa-solid-900", "fa-regular-400", "fa-brands-400", "fa-v4compatibility"):
    for _ext in ("woff2", "ttf"):
        ASSETS.append((f"{CDNJS}/font-awesome/{FONT_AWESOME}/webfonts/{_f}.{_ext}",
                       f"font-awesome/webfonts/{_f}.{_ext}"))

LICENCES = {
    "leaflet": f"Leaflet {LEAFLET} - BSD-2-Clause",
    "leaflet-draw": f"Leaflet.draw {LEAFLET_DRAW} - MIT",
    "font-awesome": (f"Font Awesome Free {FONT_AWESOME} - "
                     "CC BY 4.0 (icons), SIL OFL 1.1 (fonts), MIT (code)"),
}


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def fetch(url, dest, force=False):
    if os.path.exists(dest) and not force:
        return os.path.getsize(dest), "cached"
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    ctx = ssl.create_default_context()
    with urllib.request.urlopen(req, timeout=60, context=ctx) as r:
        data = r.read()
    with open(dest, "wb") as f:
        f.write(data)
    return len(data), "fetched"


def write_manifest(rows):
    os.makedirs(VENDOR, exist_ok=True)
    with open(MANIFEST, "w", encoding="utf-8") as f:
        f.write("Braein.ai - vendored front-end assets\n")
        f.write("=" * 78 + "\n")
        f.write("Generated by vendor_assets.py. Serves the IGA / NCSC supply-chain\n")
        f.write("review: every third-party file below is pinned, hashed and served\n")
        f.write("locally. Nothing is fetched from a CDN at runtime.\n\n")
        f.write("Licences\n--------\n")
        for v in LICENCES.values():
            f.write("  " + v + "\n")
        f.write("\nFiles\n-----\n")
        for path, size, digest, url in sorted(rows):
            f.write(f"{digest}  {size:>9}  {path}\n")
            f.write(f"{'':>64}  <- {url}\n")
        f.write(f"\n{len(rows)} files.\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--verify", action="store_true", help="check files against MANIFEST.txt")
    ap.add_argument("--force", action="store_true", help="re-fetch everything")
    args = ap.parse_args()

    if args.verify:
        if not os.path.exists(MANIFEST):
            print("No MANIFEST.txt - run without --verify first.")
            return 1
        expected = {}
        for line in open(MANIFEST, encoding="utf-8"):
            parts = line.split()
            if len(parts) >= 3 and len(parts[0]) == 64:
                expected[parts[2]] = parts[0]
        bad = missing = 0
        for rel, digest in expected.items():
            p = os.path.join(VENDOR, rel.replace("/", os.sep))
            if not os.path.exists(p):
                print(f"  MISSING  {rel}"); missing += 1
            elif sha256(p) != digest:
                print(f"  CHANGED  {rel}"); bad += 1
        if bad or missing:
            print(f"\nFAILED: {bad} changed, {missing} missing of {len(expected)}")
            return 1
        print(f"  all {len(expected)} files match the manifest")
        return 0

    rows, failed = [], 0
    for url, rel in ASSETS:
        dest = os.path.join(VENDOR, rel.replace("/", os.sep))
        try:
            size, how = fetch(url, dest, force=args.force)
            rows.append((rel, size, sha256(dest), url))
            print(f"  {how:<8} {size:>9} B  {rel}")
        except Exception as exc:
            print(f"  FAILED   {rel}  <- {url}\n           {exc}")
            failed += 1

    if rows:
        write_manifest(rows)
        print(f"\n  manifest: {MANIFEST}")
    print(f"  {len(rows)} ok, {failed} failed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
